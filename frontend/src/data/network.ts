// Vijayawada's network is chosen at build time (VITE_ITMS_NETWORK, see network.config.ts).
import rawVijayawada from "@itms-network?raw";
import amaravatiUrl from "../../../backend/data/scenarios/generated/amaravati_v2/amaravati_v2.geojson?url";
import streetNamesUrl from "@/data/street-names.json?url";
import type { Feature, FeatureCollection } from "geojson";
import { SHOWN_CITIES, type City, type CityId } from "@/data/city";
import { cumulativeLengths, haversineMeters, type LngLat } from "@/utils/geo";
import { ROAD_NAMES } from "@/data/roadNames";

/** "corridor" (the MG Road arterial) or "district" (the grid around it). */
export const networkKind: "corridor" | "district" =
  import.meta.env.VITE_ITMS_NETWORK === "district" ? "district" : "corridor";
/** What operators call the area on screen. */
export const networkName =
  networkKind === "district" ? "Central Vijayawada" : "MG Road corridor";

/** A city's network as exported from the SUMO network the simulator runs
 *  (backend/data/scenarios/networks/vijayawada/export_geojson.py). */
export interface CityNetwork {
  city: CityId;
  raw: string;
}

/** Vijayawada's network is small and bundled. Amaravati's network (~400 KB)
 *  is a separate file fetched once at startup, so it stays out of every
 *  page's JavaScript (scripts/check-bundle-budget.mjs). If it cannot be
 *  fetched the console still opens, without it. */
async function load(city: City): Promise<CityNetwork | null> {
  if (city.id === "vijayawada") return { city: city.id, raw: rawVijayawada };
  try {
    const res = await fetch(amaravatiUrl);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return { city: city.id, raw: await res.text() };
  } catch (err) {
    console.warn(`TRAFFIX: the ${city.name} road network did not load`, err);
    return null;
  }
}

/** The cities' features in one collection, each tagged with its `city`. */
export function networkFor(parts: CityNetwork[]): FeatureCollection {
  const features: Feature[] = parts.flatMap(({ city, raw }) =>
    (JSON.parse(raw) as FeatureCollection).features.map((f) => ({
      ...f,
      properties: { ...f.properties, city },
    })),
  );
  return { type: "FeatureCollection", features };
}

/** Per city and segment: the OSM street it follows (`n`) and the nearest
 *  village or neighbourhood (`a`). Generated by scripts/street-names.mjs and
 *  fetched like Amaravati's network, so it stays out of the bundle. */
type StreetNames = Partial<Record<CityId, Record<string, { n?: string; a?: string }>>>;

async function loadStreetNames(): Promise<StreetNames> {
  try {
    const res = await fetch(streetNamesUrl);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return (await res.json()) as StreetNames;
  } catch (err) {
    console.warn("TRAFFIX: street names did not load; roads are named by their class", err);
    return {};
  }
}

const [cityParts, streetNames] = await Promise.all([Promise.all(SHOWN_CITIES.map(load)), loadStreetNames()]);
const loaded = cityParts.filter((p): p is CityNetwork => p !== null);
const network = networkFor(loaded.length ? loaded : [{ city: "vijayawada", raw: rawVijayawada }]);
export interface RoadEdge {
  id: string;
  city: CityId;
  /** The street it runs along, when one is known. */
  name: string | null;
  /** The village or neighbourhood it is in, for naming unnamed roads. */
  area: string | null;
  /** OSM road class ("highway.primary"), the last resort for a label. */
  roadType: string | null;
  numLanes: number;
  speedLimitMps: number;
  path: LngLat[];
  cum: number[];
  lengthM: number;
}
/** "highway.primary" -> "Primary road": the label of last resort, for a road
 *  with no street name and no known area (street-names.json did not load). */
export function roadClassName(roadType: string | null | undefined): string | null {
  const m = /^highway\.(motorway|trunk|primary|secondary|tertiary)(_link)?$/.exec(roadType ?? "");
  if (!m) return null;
  const cls = m[1][0].toUpperCase() + m[1].slice(1);
  return m[2] ? `${cls} road link` : `${cls} road`;
}

export const roadEdges: RoadEdge[] = network.features.flatMap((f) => {
  if (f.geometry.type !== "LineString" || f.properties?.kind !== "edge")
    return [];
  const path = f.geometry.coordinates as LngLat[];
  const cum = cumulativeLengths(path);
  const id = String(f.properties.edge_id);
  const city = f.properties.city as CityId;
  const street = streetNames[city]?.[id];
  return [
    {
      id,
      city,
      name: (f.properties.name as string | null) ?? ROAD_NAMES[id] ?? street?.n ?? null,
      area: street?.a ?? null,
      roadType: (f.properties.road_type as string | null | undefined) ?? null,
      numLanes: Number(f.properties.num_lanes),
      speedLimitMps: Number(f.properties.speed_limit_mps),
      path,
      cum,
      lengthM: cum[cum.length - 1],
    },
  ];
});
export const junctions = network.features.flatMap((f) => {
  if (f.geometry.type !== "Point" || f.properties?.kind !== "junction")
    return [];
  return [
    {
      id: String(f.properties.junction_id),
      city: f.properties.city as CityId,
      lng: f.geometry.coordinates[0],
      lat: f.geometry.coordinates[1],
      isTrafficLight: Boolean(f.properties.is_traffic_light),
    },
  ];
});
export const signalJunctions = junctions.filter((j) => j.isTrafficLight);
export const edgeById = new Map(roadEdges.map((e) => [e.id, e]));
export const junctionById = new Map(junctions.map((j) => [j.id, j]));
const points = roadEdges.flatMap((e) => e.path);
export const networkBounds = {
  minLng: Math.min(...points.map((p) => p[0])),
  maxLng: Math.max(...points.map((p) => p[0])),
  minLat: Math.min(...points.map((p) => p[1])),
  maxLat: Math.max(...points.map((p) => p[1])),
};
/** A road's display name: its street, or, as Google Maps does for a road
 *  OSM has no name for, "Unnamed road, Rayapudi". */
export function roadLabel(edgeOrId: RoadEdge | string | undefined | null): string {
  const e = typeof edgeOrId === "string" ? edgeById.get(edgeOrId) : edgeOrId;
  if (!e) return "Unknown road";
  if (e.name) return e.name;
  if (e.area) return `Unnamed road, ${e.area}`;
  return roadClassName(e.roadType) ?? "Unnamed road";
}

/** "E7 to N9", or "Along E7" when a trip starts and ends on the same street. */
export function routeLabel(from: string | null | undefined, to: string | null | undefined): string {
  const a = roadLabel(from);
  const b = roadLabel(to);
  return a === b ? `Along ${a}` : `${a} to ${b}`;
}

const junctionNames = new Map<string, string>();
/** Name a junction after the streets that meet there: "MG Road at Eat Street". */
export function shortJunctionName(id: string): string {
  const cached = junctionNames.get(id);
  if (cached) return cached;
  const j = junctionById.get(id);
  let name = `Junction ${id.slice(-4)}`;
  if (j) {
    const here: LngLat = [j.lng, j.lat];
    const streets = new Set<string>();
    let area: string | null = null;
    for (const e of roadEdges) {
      const a = e.path[0];
      const b = e.path[e.path.length - 1];
      if (haversineMeters(here, a) >= 30 && haversineMeters(here, b) >= 30) continue;
      if (e.name) streets.add(e.name);
      area ??= e.area;
    }
    const list = [...streets].sort((x, y) => (x === "MG Road" ? -1 : y === "MG Road" ? 1 : x.localeCompare(y)));
    if (list.length >= 2) name = `${list[0]} at ${list[1]}`;
    else if (list.length === 1) name = `${list[0]} junction`;
    else if (area) name = `Junction, ${area}`;
  }
  junctionNames.set(id, name);
  return name;
}

/** Geographic adjacency for the illustrative browser demo only, NOT emergency routing. */
export const edgeAdjacency = new Map(
  roadEdges.map((edge) => {
    const end = edge.path[edge.path.length - 1];
    const links = roadEdges
      .filter((e) => e.id !== edge.id)
      .flatMap((e) => {
        if (haversineMeters(end, e.path[0]) < 45)
          return [{ edgeId: e.id, reversed: false }];
        if (haversineMeters(end, e.path[e.path.length - 1]) < 45)
          return [{ edgeId: e.id, reversed: true }];
        return [];
      });
    return [edge.id, links];
  }),
);

export function nearestEdge(
  point: LngLat,
  maxDistanceM = 45,
): { edge: RoadEdge; snapped: LngLat; distanceM: number } | null {
  let best: ReturnType<typeof nearestEdge> = null;
  const scale = Math.cos((point[1] * Math.PI) / 180);
  for (const edge of roadEdges) {
    for (let i = 1; i < edge.path.length; i++) {
      const a = edge.path[i - 1],
        b = edge.path[i];
      const dx = (b[0] - a[0]) * scale,
        dy = b[1] - a[1];
      const denominator = dx * dx + dy * dy;
      const t =
        denominator === 0
          ? 0
          : Math.max(
              0,
              Math.min(
                1,
                ((point[0] - a[0]) * scale * dx + (point[1] - a[1]) * dy) /
                  denominator,
              ),
            );
      const snapped: LngLat = [
        a[0] + (b[0] - a[0]) * t,
        a[1] + (b[1] - a[1]) * t,
      ];
      const distanceM = haversineMeters(point, snapped);
      if (distanceM <= maxDistanceM && (!best || distanceM < best.distanceM))
        best = { edge, snapped, distanceM };
    }
  }
  return best;
}
