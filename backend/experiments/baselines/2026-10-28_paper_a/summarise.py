"""Paper-A final benchmark: tables and target verdicts from results/*.json.

    python baselines/2026-10-28_paper_a/summarise.py > baselines/2026-10-28_paper_a/results/SUMMARY.md

Method (as every earlier baseline in this project): per seed, the % change in
total person-delay of ours against the other controller on the same seed;
mean over seeds with a t-based 95 % interval. "Avg delay" is person-delay per
scored trip (occupancy-weighted time lost, s). p95 wait is the mean over seeds
of each run's 95th-percentile waiting time.
"""
from scipy.stats import t as _t
import json
import math
import pathlib
import statistics as st
from collections import defaultdict

HERE = pathlib.Path(__file__).parent / "results"
T95 = {2: 12.706, 3: 4.303, 4: 3.182, 5: 2.776, 6: 2.571, 7: 2.447, 8: 2.365, 9: 2.306, 10: 2.262}
OURS = "truth"
NAMES = {"truth": "CC-A-CAMP (ours)", "webster:pair": "Webster", "maxpressure": "Max-pressure",
         "actuated": "Actuated (SUMO)", "presslight": "PressLight (RL)",
         "vision:itms6_640:failsafe": "ours, cameras (itms6_640)"}
LEVELS = ["light", "medium", "heavy"]


def interval(xs):
    m = st.fmean(xs)
    if len(xs) < 2 or st.stdev(xs) == 0:
        return m, m, m
    h = _t.ppf(0.975, len(xs) - 1) * st.stdev(xs) / math.sqrt(len(xs))
    return m, m - h, m + h


def load(prefix):
    """{(net, allred, level): {arm: {seed: record}}}"""
    out = defaultdict(lambda: defaultdict(dict))
    for f in sorted(HERE.glob(f"{prefix}_*.json")):
        stem = f.stem[len(prefix) + 1:]
        net, allred = stem.rsplit("_", 1)
        for r in json.loads(f.read_text())["records"]:
            arm = r.get("arm") or r["controller"]
            if r["controller"] == "presslight":
                arm = "presslight"
            out[(net, allred, r["demand_level"])][arm][r["seed"]] = r
    return out


def avg_delay(r):
    return r["person_delay_s"] / max(1, r.get("n_trips_scored") or 1)


def table(data, arms, allred, title):
    print(f"\n## {title} (all-red: {'ITE per junction' if allred == 'ite' else 'flat 2.0 s'})\n")
    print("| network | level | controller | seeds | avg delay (s/trip) | person-delay (s) | p95 wait (s) | stops/veh | teleports | unfinished | interlock viol. | ours vs this: % delay, 95 % CI | ours better on |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    verdict = {}
    for (net, ar, lvl) in sorted(data, key=lambda k: (k[0], LEVELS.index(k[2]) if k[2] in LEVELS else 9)):
        if ar != allred:
            continue
        d = data[(net, ar, lvl)]
        ours = d.get(OURS, {})
        for arm in arms:
            a = d.get(arm)
            if not a:
                continue
            seeds = sorted(a)
            cmp = ""
            if arm != OURS and ours:
                common = sorted(set(a) & set(ours))
                if len(common) >= 2:
                    rel = [(ours[s]["person_delay_s"] / a[s]["person_delay_s"] - 1) * 100 for s in common]
                    m, lo, hi = interval(rel)
                    verdict[(net, lvl, arm)] = (m, lo, hi, sum(x < 0 for x in rel), len(rel))
                    cmp = f"{m:+.1f} % [{lo:+.1f}, {hi:+.1f}] | {sum(x < 0 for x in rel)}/{len(rel)}"
            if not cmp:
                cmp = "– | –"

            def mean(key, a=a, seeds=seeds):
                return st.fmean(key(a[s]) for s in seeds)

            print(f"| {net} | {lvl} | {NAMES.get(arm, arm)} | {len(seeds)} | {mean(avg_delay):.1f} | "
                  f"{mean(lambda r: r['person_delay_s']):,.0f} | {mean(lambda r: r['wait_time_s']['p95_s']):.0f} | "
                  f"{mean(lambda r: r['stops_per_vehicle']):.2f} | {sum(a[s].get('teleports') or 0 for s in seeds)} | "
                  f"{sum(a[s].get('unfinished_at_cap') or 0 for s in seeds)} | "
                  f"{sum(a[s].get('interlock_violations') or 0 for s in seeds)} | {cmp} |")
    return verdict


def pooled(verdict, arm):
    xs = [v[0] for (n, l, a), v in verdict.items() if a == arm]
    if len(xs) < 2:
        return None
    sig_b = sum(1 for (n, l, a), v in verdict.items() if a == arm and v[2] < 0)
    sig_w = sum(1 for (n, l, a), v in verdict.items() if a == arm and v[1] > 0)
    return len(xs), *interval(xs), sig_b, sig_w


def main():
    main_ = load("main")
    print("# Paper-A final benchmark: summary (generated by summarise.py)")
    v_ite = table(main_, [OURS, "webster:pair", "maxpressure", "actuated"], "ite", "Main table")
    v_flat = table(main_, [OURS, "webster:pair"], "flat", "Same seeds, flat 2.0 s all-red")
    rl = load("rl")
    for k, v in rl.items():
        main_[k]["presslight"] = v["presslight"]
    v_rl = table({k: main_[k] for k in rl}, [OURS, "presslight", "webster:pair"], "ite", "RL baseline (ingolstadt)") if rl else {}
    print("\n## Pooled over network-levels (mean of per-network-level % changes, 95 % CI across network-levels)\n")
    print("| comparison | all-red | network-levels | mean % | 95 % CI | ours significantly better | ours significantly worse |")
    print("|---|---|---|---|---|---|---|")
    for arm in ["webster:pair", "maxpressure", "actuated"]:
        p = pooled(v_ite, arm)
        if p:
            print(f"| ours vs {NAMES[arm]} | ITE | {p[0]} | {p[1]:+.1f} | [{p[2]:+.1f}, {p[3]:+.1f}] | {p[4]} | {p[5]} |")
    p = pooled(v_flat, "webster:pair")
    if p:
        print(f"| ours vs Webster | flat 2.0 | {p[0]} | {p[1]:+.1f} | [{p[2]:+.1f}, {p[3]:+.1f}] | {p[4]} | {p[5]} |")
    p = pooled(v_rl, "presslight")
    if p:
        print(f"| ours vs PressLight | ITE | {p[0]} | {p[1]:+.1f} | [{p[2]:+.1f}, {p[3]:+.1f}] | {p[4]} | {p[5]} |")

    # cost of ITE for each controller (same seeds)
    print("\n## Cost of the ITE all-red (person-delay, ITE vs flat, same seeds)\n")
    print("| network | level | ours | Webster |")
    print("|---|---|---|---|")
    for (net, ar, lvl) in sorted(main_):
        if ar != "ite" or (net, "flat", lvl) not in main_:
            continue
        cells = []
        for arm in [OURS, "webster:pair"]:
            a, b = main_[(net, "ite", lvl)].get(arm, {}), main_[(net, "flat", lvl)].get(arm, {})
            c = sorted(set(a) & set(b))
            if len(c) >= 2:
                m, lo, hi = interval([(a[s]["person_delay_s"] / b[s]["person_delay_s"] - 1) * 100 for s in c])
                cells.append(f"{m:+.1f} % [{lo:+.1f}, {hi:+.1f}]")
            else:
                cells.append("–")
        print(f"| {net} | {lvl} | {cells[0]} | {cells[1]} |")

    # ablation
    abl = load("abl")
    if abl:
        print("\n## Ablation (ITE, seeds 279-283): person-delay with one part switched off, vs the full controller\n")
        arms = sorted({a for d in abl.values() for a in d})
        agg = defaultdict(list)
        print("| network | level | " + " | ".join(arms) + " |")
        print("|---|---|" + "---|" * len(arms))
        for k in sorted(abl, key=lambda k: (k[0], LEVELS.index(k[2]))):
            full = main_.get(k, {}).get(OURS, {})
            cells = []
            for arm in arms:
                a = abl[k][arm]
                c = sorted(set(a) & set(full))
                if len(c) >= 2:
                    rel = [(a[s]["person_delay_s"] / full[s]["person_delay_s"] - 1) * 100 for s in c]
                    m, lo, hi = interval(rel)
                    agg[arm].append(m)
                    cells.append(f"{m:+.1f} [{lo:+.1f}, {hi:+.1f}]" + (" v" if sum(a[s]["interlock_violations"] for s in c) else ""))
                else:
                    cells.append("–")
            print(f"| {k[0]} | {k[2]} | " + " | ".join(cells) + " |")
        print("\n| part switched off | network-levels | mean % change in delay | 95 % CI |")
        print("|---|---|---|---|")
        for arm, xs in agg.items():
            m, lo, hi = interval(xs)
            print(f"| {arm} | {len(xs)} | {m:+.1f} | [{lo:+.1f}, {hi:+.1f}] |")

    for prefix, arms, title in [("indian", [OURS, "webster:pair", "maxpressure", "actuated"], "Lane-less Indian traffic (sublane model)"),
                                ("camera", [OURS, "vision:itms6_640:failsafe"], "Cameras in the loop")]:
        d = load(prefix)
        if d:
            vv = table(d, arms, "ite", title)
            if prefix == "camera":
                # here the comparison column reads "perfect data vs cameras": flip the sign
                print("\n(For this table the % column is perfect sensing against cameras: "
                      "a negative value is the cost of the cameras, sign flipped.)")
            for arm in arms[1:]:
                p = pooled(vv, arm)
                if p:
                    print(f"\npooled ours vs {NAMES.get(arm, arm)}: {p[1]:+.1f} % [{p[2]:+.1f}, {p[3]:+.1f}] over {p[0]} network-levels")


if __name__ == "__main__":
    main()
